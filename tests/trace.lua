return function(h)
  local test, seed, feed, eq, plugin = h.test, h.seed, h.feed, h.eq, h.plugin
  local trace = require("pairs.trace")
  vim.cmd.runtime("plugin/pairs.lua")
  local function typed(before, keys, opts, ft)
    local entry = seed(before, ft)
    plugin.setup(opts)
    trace.clear()
    trace.start()
    feed(entry .. keys .. "<Cmd>lua pairs_test_capture()<CR><Esc>")
    trace.stop()
    assert(not trace.status().error, trace.status().error)
    return trace.entries()
  end
  local function patched(target, key, value, run)
    local original = target[key]
    target[key] = value
    local ok, err = xpcall(run, debug.traceback)
    target[key] = original
    assert(ok, err)
  end
  test("trace: disabled path never calls the recorder", function()
    local entry = seed("│")
    plugin.setup()
    trace.clear()
    eq(trace.status().active, false)
    patched(trace, "record", function()
      error("disabled trace recorded")
    end, function()
      feed(entry .. '"<Cmd>lua pairs_test_capture()<CR><Esc>')
      eq(_G.pairs_test_result, '"│"')
      eq(trace.status().count, 0)
    end)
  end)
  test("trace: query-only explain never records or exposes context", function()
    seed("│")
    plugin.setup()
    trace.clear()
    trace.start()
    eq(select("#", plugin.explain('"', { assume_insert = true })), 1)
    eq(plugin.explain('"', { assume_insert = true }).action, "pair")
    eq(trace.status().count, 0)
    trace.stop()
  end)
  test("trace: continuous input captures each pre-edit insertion boundary", function()
    local entries = typed("│", '("x")')
    eq(_G.pairs_test_result, '("x")│')
    eq(#entries, 4)
    eq(entries[1].input.line, "")
    eq(entries[1].cursor, { row = 0, col = 0 })
    eq(entries[2].input.line, "()")
    eq(entries[2].cursor.col, 1)
    eq(entries[3].input.line, '("x")')
    eq(entries[3].cursor.col, 3)
    eq(entries[3].decision.action, "skip")
    eq(entries[3].decision.reason, "matching_quote")
    eq(entries[4].cursor.col, 4)
    eq(entries[4].decision.reason, "matching_bracket")
    eq(entries[1].mode, "i")
    eq(entries[1].syntax.source, "lexer")
  end)
  test("trace: native apostrophe records the precise suppression reason", function()
    local entries = typed("don│t", "'")
    eq(_G.pairs_test_result, "don'│t")
    eq(entries[1].input.line, "dont")
    eq(entries[1].cursor.col, 3)
    eq(entries[1].decision.action, "pass")
    eq(entries[1].decision.reason, "quote_neighbor")
  end)
  test("trace: retained policy is independent of later buffer changes", function()
    local entry = seed("│")
    plugin.setup()
    trace.clear()
    trace.start()
    vim.b.pairs_rules = { ['"'] = { open = false, extra = function() end } }
    feed(entry .. '"<Esc>')
    vim.b.pairs_rules = nil
    local first = trace.entries()[1]
    eq(first.decision.reason, "opening_disabled")
    eq(first.options.filetypes.lua.pairs['"'].open, false)
    eq(first.options.filetypes.lua.pairs['"'].extra, nil)
    first.options.filetypes.lua.pairs['"'].open = true
    eq(trace.entries()[1].options.filetypes.lua.pairs['"'].open, false)
    trace.stop()
  end)
  test("trace: bounded ring preserves chronological order and reports drops", function()
    local entries = typed("│", string.rep("()", 60))
    eq(#entries, 100)
    eq(entries[1].id, 21)
    eq(entries[100].id, 120)
    eq(trace.status().dropped, 20)
    for i = 2, #entries do
      eq(entries[i].id, entries[i - 1].id + 1)
    end
  end)
  test("trace: stop retains records, start resumes and clear stays active", function()
    typed("│", "(")
    eq(trace.status().count, 1)
    plugin.handle(")") -- Normal-mode native fallback after stop is not logged.
    eq(trace.status().count, 1)
    trace.start()
    feed("a)<Esc>")
    eq(trace.status().count, 2)
    eq(trace.entries()[2].id, 2)
    trace.clear()
    eq(trace.status(), { active = true, count = 0, capacity = 100, dropped = 0 })
    feed("a(<Esc>")
    eq(trace.entries()[1].id, 1)
    trace.stop()
  end)
  test("trace: teardown stops without destroying useful records", function()
    typed("│", "(")
    trace.start()
    plugin.teardown()
    eq(trace.status().active, false)
    eq(trace.status().count, 1)
  end)
  test("trace: re-setup records the policy in effect for each key", function()
    local entry = seed("│")
    plugin.setup()
    trace.clear()
    trace.start()
    feed(entry .. "( <Esc>")
    plugin.setup({ pairs = { ["["] = { open = false } } })
    feed("a[<Esc>")
    trace.stop()
    local entries = trace.entries()
    eq(entries[1].decision.action, "pair")
    eq(entries[2].decision.reason, "opening_disabled")
    eq(entries[1].options.filetypes.lua.pairs["["].open, true)
    eq(entries[2].options.filetypes.lua.pairs["["].open, false)
  end)
  test("trace: recorder failure cannot break typing or create notifications", function()
    local entry = seed("│")
    plugin.setup()
    trace.clear()
    trace.start()
    patched(trace, "record", function()
      error("recording failure")
    end, function()
      feed(entry .. '"<Cmd>lua pairs_test_capture()<CR><Esc>')
      eq(_G.pairs_test_result, '"│"')
      eq(trace.status().active, false)
      assert(trace.status().error:find("recording failure", 1, true))
    end)
    trace.start()
    eq(trace.status().error, nil)
    trace.stop()
  end)
  test("trace: context errors preserve native input and remain inspectable", function()
    local entry = seed("│")
    plugin.setup()
    trace.clear()
    trace.start()
    vim.b.pairs_rules = { ['"'] = { close = "invalid" } }
    feed(entry .. '"<Cmd>lua pairs_test_capture()<CR><Esc>')
    eq(_G.pairs_test_result, '"│')
    local captured = trace.entries()[1]
    eq(captured.decision.reason, "context_error")
    eq(captured.syntax.source, "capture_error")
    assert(captured.decision.error:find("single printable ASCII", 1, true))
    eq(captured.options, nil)
    trace.stop()
  end)
  test("trace: composed expr records exactly once for native fallback", function()
    local entry = seed("don│t")
    plugin.setup({ mappings = { enabled = false } })
    trace.clear()
    trace.start()
    vim.keymap.set("i", "<F8>", function()
      return plugin.expr("'") or "'"
    end, { expr = true, replace_keycodes = false })
    local ok, err = xpcall(function()
      feed(entry .. "<F8><Cmd>lua pairs_test_capture()<CR><Esc>")
      eq(_G.pairs_test_result, "don'│t")
      eq(trace.status().count, 1)
      eq(trace.entries()[1].decision.reason, "quote_neighbor")
    end, debug.traceback)
    vim.keymap.del("i", "<F8>")
    trace.stop()
    assert(ok, err)
  end)
  test("trace: pre-edit byte columns retain Unicode text", function()
    local entries = typed("你好│", '"')
    eq(entries[1].cursor.col, 6)
    eq(entries[1].input.line, "你好")
    eq(entries[1].input.truncated_left, false)
    eq(entries[1].decision.reason, "quote_neighbor")
    assert(vim.json.encode(entries))
  end)
  test("trace: short lines below the text budget never lose their prefix", function()
    local before = string.rep("x ", 1500)
    local entries = typed(before .. "│", "(")
    eq(entries[1].input.line, before)
    eq(entries[1].input.start_col, 0)
    eq(entries[1].input.truncated_left, false)
    eq(entries[1].input.truncated_right, false)
  end)
  test("trace: very long Unicode lines clip on codepoint boundaries", function()
    local prefix, suffix = string.rep("你", 2000), string.rep("好", 2000)
    local entries = typed(prefix .. "│" .. suffix, "(")
    local entry = entries[1]
    eq(entry.cursor.col, #prefix)
    assert(#entry.input.line <= 4096)
    eq(entry.input.total_bytes, #prefix + #suffix)
    eq(entry.input.truncated_left, true)
    eq(entry.input.truncated_right, true)
    eq(entry.input.start_col % 3, 0)
    eq(#entry.input.line % 3, 0)
    assert(vim.json.encode(entry))
  end)
  test("trace: Enter, deletion, undo, redo and dot keep native behavior", function()
    local entries = typed("│", "(<BS>{<CR>x")
    eq(_G.pairs_test_result, "{\n  x│\n}")
    eq(entries[2].decision.action, "delete")
    eq(entries[4].decision.action, "newline")
    feed("u")
    eq(vim.api.nvim_buf_get_lines(0, 0, -1, false), { "" })
    feed("<C-r>")
    eq(vim.api.nvim_buf_get_lines(0, 0, -1, false), { "{", "  x", "}" })
    feed("u.")
    eq(vim.api.nvim_buf_get_lines(0, 0, -1, false), { "{", "  x", "}" })
  end)
  test("trace: enabled callbacks are evaluated once and are never serialized", function()
    local calls = 0
    local entries = typed("│", "(", {
      enabled = function()
        calls = calls + 1
        return true
      end,
    })
    eq(calls, 1)
    eq(entries[1].options.enabled, true)
    assert(table.concat(entries[1].limitations, " "):find("callback", 1, true))
    assert(vim.json.encode(entries))
  end)
  test("trace: export is explicit, roundtrips and refuses accidental overwrite", function()
    local entries = typed("don│t", "'")
    local path = vim.fn.tempname()
    eq(vim.fn.filereadable(path), 0)
    eq(trace.export(path), path)
    local data = vim.json.decode(table.concat(vim.fn.readfile(path), "\n"))
    eq(data.schema, 1)
    eq(data.records, entries)
    eq(data.limits.records, 100)
    eq(data.limits.line_bytes, 4096)
    assert(data.note:find("not expected assertions", 1, true))
    local original = vim.fn.readfile(path)
    eq(pcall(trace.export, path), false)
    eq(pcall(trace.export, path, "replace"), false)
    eq(vim.fn.readfile(path), original)
    trace.clear()
    trace.export(path, true)
    eq(#vim.json.decode(table.concat(vim.fn.readfile(path), "\n")).records, 0)
    vim.fn.delete(path)
  end)
  test("trace: exported local input and policy reproduce a lexer decision", function()
    typed("don│t", "'")
    local path = vim.fn.tempname()
    trace.export(path)
    local entry = vim.json.decode(table.concat(vim.fn.readfile(path), "\n")).records[1]
    vim.fn.delete(path)
    local marker = entry.cursor.col - entry.input.start_col
    local before = entry.input.line:sub(1, marker) .. "│" .. entry.input.line:sub(marker + 1)
    local mode = seed(before, entry.filetype)
    plugin.setup(entry.options)
    feed(mode .. entry.key .. "<Cmd>lua pairs_test_capture()<CR><Esc>")
    eq(_G.pairs_test_result, "don'│t") -- Human-confirmed expectation, not the observed decision.
  end)
  test("trace: export cannot follow an existing symlink without overwrite", function()
    local path, link = vim.fn.tempname(), vim.fn.tempname()
    vim.fn.writefile({ "preserve" }, path)
    assert(vim.uv.fs_symlink(path, link))
    eq(pcall(trace.export, link), false)
    eq(vim.fn.readfile(path), { "preserve" })
    vim.fn.delete(link)
    vim.fn.delete(path)
  end)
  test("trace: failed export leaves recording and entries intact", function()
    typed("│", "(")
    trace.start()
    local previous = trace.entries()
    eq(pcall(trace.export, vim.fn.tempname() .. "/missing/file.json"), false)
    eq(trace.entries(), previous)
    eq(trace.status().active, true)
    trace.stop()
  end)
  test("trace: partial write failure closes and removes a newly created export", function()
    typed("│", "(")
    local path = vim.fn.tempname()
    local entries = trace.entries()
    local original, calls = vim.uv.fs_write, 0
    patched(vim.uv, "fs_write", function(fd, text, offset)
      calls = calls + 1
      if calls == 1 then
        return original(fd, text:sub(1, 8), offset)
      end
      return nil, "ENOSPC: injected write failure"
    end, function()
      eq(pcall(trace.export, path), false)
      eq(calls, 2)
      eq(vim.uv.fs_stat(path), nil)
      eq(trace.entries(), entries)
    end)
  end)
  test("trace: an uninitialized composed call is distinguished from capture errors", function()
    seed("│")
    trace.clear()
    trace.start()
    plugin.handle('"')
    local entry = trace.entries()[1]
    eq(entry.decision.reason, "not_initialized")
    eq(entry.syntax.source, "uninitialized")
    eq(entry.options, nil)
    trace.stop()
  end)
  test("trace: long custom filetype names cannot make retained options unbounded", function()
    local entries = typed("│", "(", {}, string.rep("x", 300))
    eq(#entries[1].filetype, 128)
    eq(entries[1].options, nil)
    assert(table.concat(entries[1].limitations, " "):find("Filetype was clipped", 1, true))
  end)
  test("trace: commands control capture and show a readonly scratch buffer", function()
    typed("don│t", "'")
    eq(vim.fn.exists(":PairsTrace"), 2)
    vim.cmd.PairsTrace("start")
    eq(trace.status().active, true)
    vim.cmd.PairsTrace("stop")
    local source = vim.api.nvim_get_current_buf()
    local original = vim.api.nvim_buf_get_lines(source, 0, -1, false)
    vim.cmd.PairsTrace("show")
    local buf = vim.api.nvim_get_current_buf()
    eq(vim.bo.buftype, "nofile")
    eq(vim.bo.modifiable, false)
    eq(vim.bo.swapfile, false)
    local content = table.concat(vim.api.nvim_buf_get_lines(buf, 0, -1, false), "\n")
    assert(content:find('"don" | "t"', 1, true))
    assert(content:find("quote_neighbor", 1, true))
    eq(vim.api.nvim_buf_get_lines(source, 0, -1, false), original)
    vim.cmd.close()
    eq(vim.api.nvim_buf_is_valid(buf), false)
    eq(vim.api.nvim_get_current_buf(), source)
    vim.cmd.PairsTrace("clear")
    eq(trace.status().count, 0)
  end)
  test("trace: export command accepts an escaped path with spaces", function()
    typed("│", "(")
    local path = vim.fn.tempname() .. " trace.json"
    vim.cmd("PairsTrace export " .. vim.fn.fnameescape(path))
    eq(vim.fn.filereadable(path), 1)
    local data = vim.json.decode(table.concat(vim.fn.readfile(path), "\n"))
    eq(#data.records, 1)
    vim.cmd("PairsTrace! export " .. vim.fn.fnameescape(path))
    vim.fn.delete(path)
  end)
  test("trace: command validation and completion are explicit", function()
    eq(pcall(trace.command, { "start", "extra" }, false), false)
    eq(pcall(trace.command, { "start" }, true), false)
    eq(pcall(trace.command, { "unknown" }, false), false)
    eq(pcall(trace.command, { "export" }, false), false)
    eq(trace.complete("st", "PairsTrace st", 13), { "start", "stop" })
    eq(trace.complete("", "PairsTrace start ", 17), {})
    local path = vim.fn.tempname() .. ".json"
    vim.fn.writefile({ "" }, path)
    local cmd = "PairsTrace export " .. path
    assert(vim.tbl_contains(trace.complete(path, cmd, #cmd), path))
    vim.fn.delete(path)
  end)
  if vim.env.PAIRS_TEST_PARSER_ROOT then
    test("trace: real parser literal context is retained without the tree", function()
      local entries = typed('value = """\nbody│\n"""', "(", { treesitter = true }, "python")
      eq(entries[1].cursor.row, 1)
      eq(entries[1].input.line, "body")
      eq(entries[1].syntax.source, "treesitter")
      eq(entries[1].syntax.classification, "string")
      eq(entries[1].syntax.literal_string, true)
      eq(entries[1].decision.reason, "literal_string")
      assert(table.concat(entries[1].limitations, " "):find("Surrounding lines", 1, true))
    end)
    test("trace: pending parser is logged without a second parse request", function()
      local entry = seed("value = │", "python")
      plugin.setup({ treesitter = true })
      local parser = vim.treesitter.get_parser(0, "python")
      parser:parse(true)
      vim.api.nvim_buf_set_lines(0, 0, -1, false, { "value = " })
      trace.clear()
      trace.start()
      local calls = 0
      patched(parser, "parse", function(_, range, callback)
        calls = calls + 1
        eq(type(range), "table")
        eq(type(callback), "function")
        return nil
      end, function()
        feed(entry .. '"<Cmd>lua pairs_test_capture()<CR><Esc>')
        eq(_G.pairs_test_result, 'value = "│')
        eq(calls, 1)
        local event = trace.entries()[1]
        eq(event.syntax.classification, "unknown")
        eq(event.decision.reason, "syntax_pending")
      end)
      trace.stop()
    end)
  end
  trace.stop()
  trace.clear()
end
